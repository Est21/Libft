#include "libft.h"

int	ft_strncmp(const char *s1, const char *s2, size_t n)
{
	size_t			i;
	unsigned char	*ptr1;
	unsigned char	*ptr2;

	ptr1 = (unsigned char *)s1;
	ptr2 = (unsigned char *)s2;
	i = 0;
	if (n == 0)
		return (0);
	while ((ptr1[i] != '\0' && ptr2[i] != '\0')
		&& (i < (n - 1)) && (ptr1[i] == ptr2[i]))
		i++;
	return (ptr1[i] - ptr2[i]);
}
